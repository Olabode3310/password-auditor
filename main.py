import argparse,json,time
from pathlib import Path
from hashers.verify import SUPPORTED
from attackers.dictionary import attack
from strength.estimate import estimate

def main():
 p=argparse.ArgumentParser(description='Offline password strength and authorized hash audit tool.')
 sub=p.add_subparsers(dest='command',required=True)
 s=sub.add_parser('strength');s.add_argument('password')
 a=sub.add_parser('audit');a.add_argument('--hash-type',choices=SUPPORTED,required=True);a.add_argument('--hash-file',required=True,help='One encoded hash per line');a.add_argument('--wordlist',default='wordlists/sample.txt');a.add_argument('--workers',type=int,default=1);a.add_argument('--output')
 x=p.parse_args()
 if x.command=='strength':print(json.dumps(estimate(x.password),indent=2));return 0
 if not 1<=x.workers<=8:p.error('workers must be 1-8')
 hashes=[h.strip() for h in Path(x.hash_file).read_text(encoding='utf8').splitlines() if h.strip() and not h.startswith('#')];words=[w.strip() for w in Path(x.wordlist).read_text(encoding='utf8').splitlines() if w.strip() and not w.startswith('#')]
 start=time.monotonic();results=[]
 try:
  for value in hashes:
   cracked=attack(x.hash_type,value,words,x.workers)
   results.append({'hash':value,'status':'cracked' if cracked is not None else 'uncracked','password':cracked,'strength':estimate(cracked) if cracked else None})
 except RuntimeError as e:p.error(str(e))
 elapsed=round(time.monotonic()-start,3);report={'hash_type':x.hash_type,'hashes_checked':len(results),'elapsed_seconds':elapsed,'results':results,'recommendations':['Use unique passwords generated by a password manager.','Enable MFA where available.','Use a slow password hash such as bcrypt or Argon2 for stored credentials.']}
 out=json.dumps(report,indent=2)
 if x.output:Path(x.output).write_text(out+'\n',encoding='utf8')
 else:print(out)
 return 0
if __name__=='__main__':raise SystemExit(main())
